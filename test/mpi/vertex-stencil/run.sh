#!/usr/bin/env bash
#===============================================================================
#  Viscous block-connection stencil at a vertex shared by four blocks,
#  under MPI (needs-mpi tier)
#
#  The viscous flux on a block connection uses the source cell's tangential
#  neighbours (bc%Pg(:,3:6)). At a vertex where blocks owned by different
#  ranks meet, some of those neighbours are ghost cells that arrive through
#  the MPI exchange, so they may only be read after the receives complete.
#  This test asserts that the solution of a 2x2-block viscous box with a
#  vortex on the common vertex is bit-identical on
#      1x1 (reference), 1x4, 2x1, 4x1 and 2x2   (MPI ranks x OpenMP threads).
#  The same box with chemistry = equilibrium (the air as one species of one
#  element, INPUT/composition.txt: its equilibrium leaves the state as it is)
#  must give the bits of 1x1 on 2x1: each rank computes the equilibrium of its
#  own blocks only (the state of the blocks of the other ranks is not
#  allocated there).
#  The case is generated by ../make_case.py; nothing else is stored here.
#===============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

MASTER=../../../bin/MOSE
LOCAL=./bin/MOSE
COMMON=../../common/Air-viscous
MPIEXEC=${MOSE_MPIEXEC:-mpiexec}
NPFLAG=${MOSE_MPIEXEC_NUMPROC_FLAG:--n}
CASE="--layout 2x2 --cells 16 16 --bc box --zfaces 300"

ulimit -s unlimited 2>/dev/null || true
export KMP_STACKSIZE=100M

mkdir -p bin INPUT
if [[ ! -x "$LOCAL" || "$MASTER" -nt "$LOCAL" ]]; then
  cp "$MASTER" "$LOCAL"
fi
ln -sf "../$COMMON/phase.txt"     INPUT/phase.txt
ln -sf "../$COMMON/thermo.dat"    INPUT/thermo.dat
ln -sf "../$COMMON/transport.dat" INPUT/transport.dat
rm -f INPUT/composition.txt

cat > input.ini <<'EOF'
[MOSE-Parameters]
iter-threshold = 40
res-threshold  = 1e-300
newrun         = true

[MOSE-Physics]
equations = navier-stokes
schmidt   = 1.0

[MOSE-Numerics]
cfl                   = 0.3
vnn                   = 0.3
time-accurate         = true
time-scheme           = RK3
integration-variables = cons
space-reconstruction  = MUSCL
flux-limiter          = vanleer
riemann-solver        = HLLC

[MOSE-IO]
sol-format  = vtk raw
sol-diter   = 1000000000
shell-diter = 1000000000
ini-diter   = 1000000000
EOF

fail() { echo "MPIVertexStencil: FAIL — $*"; exit 1; }

# run <ranks> <threads> <label>: solve and keep OUTPUT as runs/<label>
run() {
  local np="$1" nt="$2" label="$3"
  rm -rf OUTPUT "runs/$label"
  mkdir -p OUTPUT/vtk runs
  if ! OMP_NUM_THREADS="$nt" "$MPIEXEC" "$NPFLAG" "$np" "$LOCAL" > "solve_$label.log" 2>&1; then
    tail -20 "solve_$label.log"; fail "solver exited non-zero ($label)"
  fi
  ls OUTPUT/vtk/fieldBlock*.vts > /dev/null 2>&1 || fail "no field output ($label)"
  mv OUTPUT "runs/$label"
}

# same <label-a> <label-b> <glob...>: every listed output file byte-identical
same() {
  local a="$1" b="$2" f n=0; shift 2
  for f in "$@"; do
    for x in runs/"$a"/$f; do
      [[ -f "$x" ]] || continue
      n=$((n + 1))
      cmp -s "$x" "runs/$b/${x#runs/$a/}" || { echo "  differs: ${x#runs/$a/} ($a vs $b)"; return 1; }
    done
  done
  [[ $n -gt 0 ]] || { echo "  nothing compared ($a vs $b)"; return 1; }
  echo "  identical: $a vs $b ($n files)"
}

status=0
python3 -B ../make_case.py $CASE > /dev/null || fail "case generation"
run 1 1 1x1
for cfg in 1x4 2x1 4x1 2x2; do
  run "${cfg%x*}" "${cfg#*x}" "$cfg"
  same 1x1 "$cfg" 'vtk/*.vts' residual-history.dat || status=1
done

# The same box with equilibrium chemistry: the air as one species of one element
printf '1\nAir\n\ncomposition\n1\n' > INPUT/composition.txt
sed -i 's/^schmidt   = 1.0$/schmidt   = 1.0\nchemistry = equilibrium/' input.ini
grep -q '^chemistry = equilibrium$' input.ini || fail "input.ini with chemistry"
run 1 1 chem-1x1
run 2 1 chem-2x1
same chem-1x1 chem-2x1 'vtk/*.vts' residual-history.dat || status=1

if [[ $status -ne 0 ]]; then
  echo "MPIVertexStencil: FAIL"
  exit 1
fi
echo "MPIVertexStencil: ok — 1x1, 1x4, 2x1, 4x1 and 2x2 bit-identical; with equilibrium chemistry 1x1 and 2x1 too"
exit 0
