#!/usr/bin/env bash
#===============================================================================
#  Boundary records under MPI (needs-mpi tier)
#
#  BC_Fluxes must visit only the boundary records of the blocks a rank owns,
#  grouped by block and face, and give the same answer as the serial run.
#  Two invariants are asserted, both bit-for-bit:
#   1. ranks x threads: a strip of four viscous blocks with inlet, outlet,
#      wall, symmetry and block-cut records gives the same solution on
#      1x1, 2x1, 4x1 and 2x2 (MPI ranks x OpenMP threads);
#   2. record order: the same case with the bc.txt records written in reverse
#      order gives the same solution as the ordered file, on 1 and 2 ranks,
#      with and without threads (1x1, 2x1, 2x2, 1x4): every face of every cell
#      is summed in the same order whatever the order of the file, and threads
#      never share a target cell inside one worksharing loop;
#   3. wall output: with the reversed file the wall output is the one of the
#      ordered file (1x1, 2x1, 1x4), written in Tecplot ASCII;
#   4. the same with the Spalart-Allmaras model in a time-accurate run, whose
#      time step also fills the ghost cells behind the walls on its own
#      (Turbulence_Stiffness): ordered file on 1x1, 1x4 and 2x2, reversed file on
#      1x1, 1x4 and 2x2, solution and wall output in Tecplot.
#  The case is generated by ../make_case.py; nothing else is stored here.
#===============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

MASTER=../../../bin/MOSE
LOCAL=./bin/MOSE
COMMON=../../common/Air-viscous
MPIEXEC=${MOSE_MPIEXEC:-mpiexec}
NPFLAG=${MOSE_MPIEXEC_NUMPROC_FLAG:--n}
CASE="--layout 4x1 --cells 16 16 --bc channel --zfaces 300"

ulimit -s unlimited 2>/dev/null || true
export KMP_STACKSIZE=100M

mkdir -p bin INPUT
if [[ ! -x "$LOCAL" || "$MASTER" -nt "$LOCAL" ]]; then
  cp "$MASTER" "$LOCAL"
fi
ln -sf "../$COMMON/phase.txt"     INPUT/phase.txt
ln -sf "../$COMMON/thermo.dat"    INPUT/thermo.dat
ln -sf "../$COMMON/transport.dat" INPUT/transport.dat

write_ini() {   # write_ini <sol-format> [line for MOSE-Physics]
cat > input.ini <<EOF
[MOSE-Parameters]
iter-threshold = 40
res-threshold  = 1e-300
newrun         = true

[MOSE-Physics]
equations = navier-stokes
schmidt   = 1.0
${2:-}

[MOSE-Numerics]
cfl                   = 0.3
vnn                   = 0.3
time-accurate         = true
time-scheme           = RK3
integration-variables = cons
space-reconstruction  = MUSCL
flux-limiter          = vanleer
riemann-solver        = HLLC

[MOSE-IO]
sol-format  = $1
sol-diter   = 1000000000
shell-diter = 1000000000
ini-diter   = 1000000000
EOF
}
write_ini "vtk raw"

fail() { echo "MPIBoundaryRecords: FAIL — $*"; exit 1; }

# run <ranks> <threads> <label>: solve and keep OUTPUT as runs/<label>
run() {
  local np="$1" nt="$2" label="$3"
  rm -rf OUTPUT "runs/$label"
  mkdir -p OUTPUT/vtk runs
  if ! OMP_NUM_THREADS="$nt" "$MPIEXEC" "$NPFLAG" "$np" "$LOCAL" > "solve_$label.log" 2>&1; then
    tail -20 "solve_$label.log"; fail "solver exited non-zero ($label)"
  fi
  ls OUTPUT/vtk/fieldBlock*.vts > /dev/null 2>&1 || ls OUTPUT/field.tec > /dev/null 2>&1 || \
    fail "no field output ($label)"
  mv OUTPUT "runs/$label"
}

# same <label-a> <label-b> <glob...>: every listed output file byte-identical
same() {
  local a="$1" b="$2" f n=0; shift 2
  for f in "$@"; do
    for x in runs/"$a"/$f; do
      [[ -f "$x" ]] || continue
      n=$((n + 1))
      cmp -s "$x" "runs/$b/${x#runs/$a/}" || { echo "  differs: ${x#runs/$a/} ($a vs $b)"; return 1; }
    done
  done
  [[ $n -gt 0 ]] || { echo "  nothing compared ($a vs $b)"; return 1; }
  echo "  identical: $a vs $b ($n files)"
}

status=0

# --- 1. ranks x threads, ordered bc.txt --------------------------------------
python3 -B ../make_case.py $CASE > /dev/null || fail "case generation"
run 1 1 1x1
for cfg in 2x1 4x1 2x2; do
  run "${cfg%x*}" "${cfg#*x}" "$cfg"
  same 1x1 "$cfg" 'vtk/*.vts' residual-history.dat || status=1
done

# --- 2. records in reverse order ---------------------------------------------
python3 -B ../make_case.py $CASE --reverse > /dev/null || fail "case generation (reverse)"
for cfg in 1x1 2x1 2x2 1x4; do
  run "${cfg%x*}" "${cfg#*x}" "rev-$cfg"
  # the solution field here; the wall output in section 3
  same 1x1 "rev-$cfg" 'vtk/fieldBlock*.vts' || status=1
done

# --- 3. wall output with the records in reverse order (Tecplot) --------------
write_ini "tecplot ascii"
python3 -B ../make_case.py $CASE > /dev/null || fail "case generation (Tecplot)"
run 1 1 tec-1x1
python3 -B ../make_case.py $CASE --reverse > /dev/null || fail "case generation (Tecplot, reverse)"
for cfg in 1x1 2x1 1x4; do
  run "${cfg%x*}" "${cfg#*x}" "tec-rev-$cfg"
  same tec-1x1 "tec-rev-$cfg" field.tec wall.tec || status=1
done

# --- 4. Spalart-Allmaras, ordered and reversed records (Tecplot) -------------
write_ini "tecplot ascii" "turbulence = SA"
python3 -B ../make_case.py $CASE --turbulence SA > /dev/null || fail "case generation (SA)"
run 1 1 sa-1x1
for cfg in 1x4 2x2; do
  run "${cfg%x*}" "${cfg#*x}" "sa-$cfg"
  same sa-1x1 "sa-$cfg" field.tec wall.tec residual-history.dat || status=1
done
python3 -B ../make_case.py $CASE --turbulence SA --reverse > /dev/null || fail "case generation (SA, reverse)"
for cfg in 1x1 1x4 2x2; do
  run "${cfg%x*}" "${cfg#*x}" "sa-rev-$cfg"
  same sa-1x1 "sa-rev-$cfg" field.tec wall.tec || status=1
done

if [[ $status -ne 0 ]]; then
  echo "MPIBoundaryRecords: FAIL"
  exit 1
fi
echo "MPIBoundaryRecords: ok — ranks x threads and record order bit-identical, wall output included, laminar and SA"
exit 0
