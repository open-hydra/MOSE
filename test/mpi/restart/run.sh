#!/usr/bin/env bash
#===============================================================================
#  Exact restart from vtk raw on 2 MPI ranks x 2 OpenMP threads (needs-mpi tier)
#
#  The 2x2-block viscous box of ../make_case.py, solved
#     full    : 40 RK3 steps in one go
#     restart : 24 steps, then newrun=false for 16 more
#  on 2 ranks x 2 threads, with numbered solutions every 8 steps
#  (sol-overwrite = false: the first part, the run in one go and the restart
#  end on an output step, which writes its numbered solution before the final
#  one, and the restart goes on from that final solution in the same folder)
#  and a CFL ramp over the first 30 steps. vtk raw keeps every bit, so the two
#  OUTPUT/ trees must be identical byte for byte: the field and wall
#  solutions, their TIME, the output numbering and residual-history.dat with
#  its iteration column.
#  The case is generated by ../make_case.py; nothing else is stored here.
#===============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

MASTER=../../../bin/MOSE
LOCAL=./bin/MOSE
COMMON=../../common/Air-viscous
MPIEXEC=${MOSE_MPIEXEC:-mpiexec}
NPFLAG=${MOSE_MPIEXEC_NUMPROC_FLAG:--n}
CASE="--layout 2x2 --cells 16 16 --bc box --zfaces 300"
NP=2; NT=2; N=40; HALF=24

fail() { echo "MPIRestart: FAIL — $*"; exit 1; }

ulimit -s unlimited 2>/dev/null || true
export KMP_STACKSIZE=100M

mkdir -p bin
if [[ ! -x "$LOCAL" || "$MASTER" -nt "$LOCAL" ]]; then
  cp "$MASTER" "$LOCAL"
fi

write_input() {  # <iter-threshold> <newrun>
  cat > input.ini <<EOI
[MOSE-Parameters]
iter-threshold = $1
res-threshold  = 1e-300
newrun         = $2

[MOSE-Physics]
equations = navier-stokes
schmidt   = 1.0

[MOSE-Numerics]
cfl                   = 0.3
vnn                   = 0.3
cfl-rise-threshold    = 30
time-accurate         = true
time-scheme           = RK3
integration-variables = cons
space-reconstruction  = MUSCL
flux-limiter          = vanleer
riemann-solver        = HLLC

[MOSE-IO]
sol-format    = vtk raw
sol-diter     = 8
sol-overwrite = false
shell-diter   = 1000000000
ini-diter     = 1000000000
EOI
}

# prepare <run directory>: inputs of the generated case
prepare() {
  rm -rf "$1"; mkdir -p "$1/INPUT" "$1/OUTPUT/vtk"
  python3 -B ../make_case.py $CASE --outdir "$1" > /dev/null || fail "case generation"
  for f in phase.txt thermo.dat transport.dat; do
    ln -s "../../../$COMMON/$f" "$1/INPUT/$f"
  done
}

# solve <run directory> <label>
solve() {
  ( cd "$1" && OMP_NUM_THREADS="$NT" "$MPIEXEC" "$NPFLAG" "$NP" "../../$LOCAL" > "solve_$2.log" 2>&1 ) \
    || { tail -20 "$1/solve_$2.log"; fail "solver exited non-zero ($2)"; }
  # MOSE's own error lines only ([ERROR] lines, the stop of a diverging run, the stops of every rank, the runtime errors
  # of the compilers): the log also holds the output of mpiexec, whose lines are not MOSE's.
  if command grep -q -E 'NaN|Integration failed|\[ERROR\]|ERROR STOP|STOP: |ABORT: |MPI error code|Fortran runtime error|Program received signal|forrtl: ' "$1/solve_$2.log"; then
    command grep -E 'NaN|Integration failed|\[ERROR\]|ERROR STOP|STOP: |ABORT: |MPI error code|Fortran runtime error|Program received signal|forrtl: ' "$1/solve_$2.log" | head -5; fail "the solver stopped with an error ($2)"
  fi
}

prepare runs/full
( cd runs/full && write_input "$N" true ); solve runs/full full
prepare runs/restart
( cd runs/restart && write_input "$HALF" true ); solve runs/restart half
( cd runs/restart && write_input "$((N - HALF))" false ); solve runs/restart restart

python3 -B ../../fast/restart/check_restart_vtk.py runs/full/OUTPUT runs/restart/OUTPUT \
  || fail "the restarted run differs from the uninterrupted one"
echo "MPIRestart: ok — restart on ${NP}x${NT} bit-identical to the uninterrupted run"
exit 0
