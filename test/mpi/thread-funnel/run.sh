#!/usr/bin/env bash
#===============================================================================
#  MPI calls only from the main thread (needs-mpi tier)
#
#  MOSE initialises MPI with MPI_THREAD_FUNNELED: the MPI standard then allows
#  MPI calls only from the thread that called MPI_INIT_THREAD. The halo and
#  IRS residual exchanges run inside the OpenMP parallel region of the RK
#  stages, so every MPI call there must be made by that thread. A probe
#  library preloaded into the solver (mpi_thread_probe.c, built with the
#  tests) counts the MPI calls made by any other thread; this test asserts
#  that the count is zero on every rank for
#      2x2, 2x4 and 2x2 with implicit residual smoothing
#  (MPI ranks x OpenMP threads), and that the probe did intercept the halo
#  exchange on every rank (otherwise the zero would mean nothing). The probe
#  also reports the largest tag of the point-to-point calls: the test asserts
#  it is at most 32767, the least MPI_TAG_UB the MPI standard allows (MPI 4.1,
#  Sec. 3.2.3). The run with residual smoothing is steady: residual smoothing
#  accelerates the convergence to a steady state, it does not keep a run
#  time-accurate.
#  The case is generated by ../make_case.py; nothing else is stored here.
#===============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

MASTER=../../../bin/MOSE
LOCAL=./bin/MOSE
COMMON=../../common/Air-viscous
MPIEXEC=${MOSE_MPIEXEC:-mpiexec}
NPFLAG=${MOSE_MPIEXEC_NUMPROC_FLAG:--n}
PROBE=${MOSE_MPI_THREAD_PROBE:-}
CASE="--layout 2x2 --cells 16 16 --bc box --zfaces 300"

fail() { echo "MPIThreadFunnel: FAIL — $*"; exit 1; }
[[ -n "$PROBE" && -f "$PROBE" ]] || fail "probe library not found (MOSE_MPI_THREAD_PROBE='$PROBE')"

ulimit -s unlimited 2>/dev/null || true
export KMP_STACKSIZE=100M

mkdir -p bin INPUT
if [[ ! -x "$LOCAL" || "$MASTER" -nt "$LOCAL" ]]; then
  cp "$MASTER" "$LOCAL"
fi
ln -sf "../$COMMON/phase.txt"     INPUT/phase.txt
ln -sf "../$COMMON/thermo.dat"    INPUT/thermo.dat
ln -sf "../$COMMON/transport.dat" INPUT/transport.dat

# input.ini; $1 = an extra [MOSE-Numerics] line (kept inside the key block:
# the ini reader stops a section at the first blank line); TA = time-accurate
# (true unless set)
write_input() {
  {
    printf '%s\n' '[MOSE-Parameters]' 'iter-threshold = 40' 'res-threshold  = 1e-300' \
                  'newrun         = true' ''
    printf '%s\n' '[MOSE-Physics]' 'equations = navier-stokes' 'schmidt   = 1.0' ''
    printf '%s\n' '[MOSE-Numerics]' 'cfl                   = 0.3' 'vnn                   = 0.3' \
                  "time-accurate         = ${TA:-true}" 'time-scheme           = RK3' \
                  'integration-variables = cons' 'space-reconstruction  = MUSCL' \
                  'flux-limiter          = vanleer' 'riemann-solver        = HLLC'
    [[ -n "${1:-}" ]] && printf '%s\n' "$1"
    printf '%s\n' '' '[MOSE-IO]' 'sol-format  = vtk raw' 'sol-diter   = 1000000000' \
                  'shell-diter = 1000000000' 'ini-diter   = 1000000000' 'timer-diter = 10'
  } > input.ini
}

python3 -B ../make_case.py $CASE > /dev/null || fail "case generation"

status=0
for run in 2x2 2x4 2x2-irs; do
  cfg=${run%%-*}
  np=${cfg%x*}; nt=${cfg#*x}
  if [[ $run == *-irs ]]; then TA=false write_input 'irs-beta              = 0.5'; else write_input; fi
  rm -rf OUTPUT; mkdir -p OUTPUT/vtk
  if ! OMP_NUM_THREADS="$nt" "$MPIEXEC" "$NPFLAG" "$np" env LD_PRELOAD="$PROBE" "$LOCAL" \
       > "solve_$run.log" 2> "probe_$run.log"; then
    tail -n 20 "solve_$run.log" "probe_$run.log"; fail "solver exited non-zero ($run)"
  fi
  # with a single thread every call would come from the main thread: the check
  # means something only if the launcher passed OMP_NUM_THREADS to the ranks
  command grep -qE "Number of threads --> *${nt}\$" "solve_$run.log" \
    || fail "solver did not run with $nt threads ($run)"
  if [[ $run == *-irs ]]; then
    command grep -q 'Beta set to' "solve_$run.log" || fail "implicit residual smoothing not active ($run)"
  fi
  lines=$(command grep -c '^MPI-THREAD-PROBE ' "probe_$run.log")
  [[ "$lines" -eq "$np" ]] || fail "expected $np probe reports, found $lines ($run)"
  # the exchange must have been seen on every rank: MPI_STARTALL is posted at every stage
  seen=$(command grep '^MPI-THREAD-PROBE ' "probe_$run.log" | command grep -c ' mpi_startall_:[1-9]')
  [[ "$seen" -eq "$np" ]] || fail "probe did not intercept the halo exchange on every rank ($run)"
  bad=$(command grep '^MPI-THREAD-PROBE ' "probe_$run.log" | command grep -vc ' other=0 ')
  if [[ "$bad" -ne 0 ]]; then
    echo "  $run: MPI calls from threads other than the main thread:"
    command grep '^MPI-THREAD-PROBE ' "probe_$run.log" | command grep -v ' other=0 ' | sed 's/^/    /'
    status=1
  else
    echo "  $run: all MPI calls from the main thread on every rank"
  fi
  maxtag=$(command grep '^MPI-THREAD-PROBE ' "probe_$run.log" | command grep -o ' maxtag=-\?[0-9]*' \
           | cut -d= -f2 | sort -n | tail -1)
  [[ -n "$maxtag" ]] || fail "probe did not report the largest tag ($run)"
  if [[ "$maxtag" -gt 32767 ]]; then
    echo "  $run: MPI tag $maxtag above 32767, the least MPI_TAG_UB the MPI standard allows"
    status=1
  else
    echo "  $run: largest MPI tag $maxtag"
  fi
done

if [[ $status -ne 0 ]]; then
  echo "MPIThreadFunnel: FAIL"
  exit 1
fi
echo "MPIThreadFunnel: ok — MPI called only by the main thread, tags at most 32767 (2x2, 2x4, 2x2 with IRS)"
exit 0
