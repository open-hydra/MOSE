#!/usr/bin/env bash
#===============================================================================
#  Wall output files (fast tier)
#
#  A viscous run on a 2x2-block box of 8 x 8 cells with adiabatic no-slip
#  walls (301) on its four sides, 5 RK3 steps, written as vtk raw, must end
#  and write one wallB<b>F<f>.vts file for each wall face. check_wall_vts.py
#  checks that each has the extent of its face, taken from the WholeExtent of
#  fieldBlock<b>.vts, as WholeExtent and as Piece Extent, holds the points
#  of that extent and one value of each wall variable per cell of the face
#  (a direction with one plane of nodes counts one layer of cells, as in the
#  cell-centered ordered data of the Tecplot format and in the writers of
#  ORION), as raw appended data. The case is generated by
#  ../../../mpi/make_case.py; nothing else is stored here.
#===============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

MASTER=../../../../bin/MOSE
LOCAL=./bin/MOSE
COMMON=../../../common/Air-viscous

ulimit -s unlimited 2>/dev/null || true
export KMP_STACKSIZE=100M
export OMP_NUM_THREADS=${OMP_NUM_THREADS:-1}

mkdir -p bin INPUT
if [[ ! -x "$LOCAL" || "$MASTER" -nt "$LOCAL" ]]; then
  cp "$MASTER" "$LOCAL"
fi
ln -sf "../$COMMON/phase.txt"     INPUT/phase.txt
ln -sf "../$COMMON/thermo.dat"    INPUT/thermo.dat
ln -sf "../$COMMON/transport.dat" INPUT/transport.dat

cat > input.ini <<'EOF'
[MOSE-Parameters]
iter-threshold = 5
res-threshold  = 1e-300
newrun         = true

[MOSE-Physics]
equations = navier-stokes
schmidt   = 1.0

[MOSE-Numerics]
cfl                   = 0.3
vnn                   = 0.3
time-accurate         = true
time-scheme           = RK3
integration-variables = cons
space-reconstruction  = MUSCL
flux-limiter          = vanleer
riemann-solver        = HLLC

[MOSE-IO]
sol-format  = vtk raw
sol-diter   = 1000000000
shell-diter = 1000000000
ini-diter   = 1000000000
EOF

fail() { echo "WallOutput: FAIL — $*"; exit 1; }

python3 -B ../../../mpi/make_case.py --layout 2x2 --cells 8 8 --bc box --zfaces 300 > /dev/null || fail "case generation"
rm -rf OUTPUT
mkdir -p OUTPUT/vtk
echo "-- vtk raw: a 2x2-block box with no-slip walls on its four sides --"
"$LOCAL" > solve.log 2>&1 || fail "the run did not end (solve.log)"
[[ -f OUTPUT/wall.vtm ]] || fail "no wall output OUTPUT/wall.vtm (solve.log)"
python3 -B check_wall_vts.py OUTPUT/vtk "vtk raw" || fail "wall files"
echo "WallOutput: ok — every vtk wall file has the extent, the points and the cell values of its face"
exit 0
