#!/usr/bin/env bash
#===============================================================================
#  VTK output files are well-formed XML with the right variable names (fast)
#
#  A steady viscous run on a 2x2-block box with no-slip walls, written as
#  vtk raw, produces the three VTK outputs of MOSE: the field (field.vtm), the
#  wall quantities (wall.vtm) and the diagnostic residuals (diagnostic.vtm).
#  check_vtk_names.py parses every .vtm and the XML part of every .vts it
#  lists (the part before the raw appended data) and compares the DataArray
#  names with the variables MOSE writes. The same with the Spalart-Allmaras
#  model and sol-variables = thermo transport (laminar viscosity and
#  conductivity, eddy viscosity). The three writers decide the paths and the
#  vtk format each on its own: the block files must be listed the same way
#  (vtk/<file>.vts) and every data array must have the format of sol-format,
#  with vtk raw and with vtk ascii. The case is generated by
#  ../../../mpi/make_case.py; nothing else is stored here.
#===============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

MASTER=../../../../bin/MOSE
LOCAL=./bin/MOSE
COMMON=../../../common/Air-viscous

ulimit -s unlimited 2>/dev/null || true
export KMP_STACKSIZE=100M
export OMP_NUM_THREADS=${OMP_NUM_THREADS:-1}

mkdir -p bin INPUT
if [[ ! -x "$LOCAL" || "$MASTER" -nt "$LOCAL" ]]; then
  cp "$MASTER" "$LOCAL"
fi
ln -sf "../$COMMON/phase.txt"     INPUT/phase.txt
ln -sf "../$COMMON/thermo.dat"    INPUT/thermo.dat
ln -sf "../$COMMON/transport.dat" INPUT/transport.dat

# write_input <extra Physics line> <extra IO line> [sol-format]
write_input() {
cat > input.ini <<EOI
[MOSE-Parameters]
iter-threshold = 5
res-threshold  = 1e-300
newrun         = true

[MOSE-Physics]
equations = navier-stokes
schmidt   = 1.0
$1

[MOSE-Numerics]
cfl                   = 0.5
time-accurate         = false
time-scheme           = RK3
integration-variables = cons
space-reconstruction  = MUSCL
flux-limiter          = vanleer
riemann-solver        = HLLC

[MOSE-IO]
sol-format  = ${3:-vtk raw}
shell-diter = 1000000000
$2
EOI
}

write_input "" ""
python3 -B ../../../mpi/make_case.py --layout 2x2 --cells 8 8 --bc box --zfaces 300 > /dev/null \
  || { echo "VtkNames: FAIL — case generation"; exit 1; }
rm -rf OUTPUT; mkdir -p OUTPUT
"$LOCAL" > solve.log 2>&1 || { tail -20 solve.log; echo "VtkNames: FAIL — solver exited non-zero"; exit 1; }
python3 -B check_vtk_names.py OUTPUT || exit 1

# the same case written as vtk ascii
write_input "" "" "vtk ascii"
rm -rf OUTPUT; mkdir -p OUTPUT
"$LOCAL" > solve-ascii.log 2>&1 || { tail -20 solve-ascii.log; echo "VtkNames: FAIL — solver exited non-zero (vtk ascii)"; exit 1; }
python3 -B check_vtk_names.py OUTPUT ascii || exit 1

# Spalart-Allmaras, with the transport properties and the eddy viscosity in the field
write_input "turbulence = SA" "sol-variables = thermo transport"
python3 -B ../../../mpi/make_case.py --layout 2x2 --cells 8 8 --bc box --zfaces 300 --turbulence SA > /dev/null \
  || { echo "VtkNames: FAIL — case generation (SA)"; exit 1; }
rm -rf OUTPUT; mkdir -p OUTPUT
"$LOCAL" > solve-sa.log 2>&1 || { tail -20 solve-sa.log; echo "VtkNames: FAIL — solver exited non-zero (SA)"; exit 1; }
python3 -B check_vtk_names.py OUTPUT sa-transport
