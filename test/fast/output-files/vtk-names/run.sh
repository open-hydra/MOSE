#!/usr/bin/env bash
#===============================================================================
#  VTK output files are well-formed XML with the right variable names (fast)
#
#  A steady viscous run on a 2x2-block box with no-slip walls, written as
#  vtk raw, produces the three VTK outputs of MOSE: the field (field.vtm), the
#  wall quantities (wall.vtm) and the diagnostic residuals (diagnostic.vtm).
#  check_vtk_names.py parses every .vtm and the XML part of every .vts it
#  lists (the part before the raw appended data) and compares the DataArray
#  names with the variables MOSE writes. The case is generated by
#  ../../../mpi/make_case.py; nothing else is stored here.
#===============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE"

MASTER=../../../../bin/MOSE
LOCAL=./bin/MOSE
COMMON=../../../common/Air-viscous

ulimit -s unlimited 2>/dev/null || true
export KMP_STACKSIZE=100M
export OMP_NUM_THREADS=${OMP_NUM_THREADS:-1}

mkdir -p bin INPUT
if [[ ! -x "$LOCAL" || "$MASTER" -nt "$LOCAL" ]]; then
  cp "$MASTER" "$LOCAL"
fi
ln -sf "../$COMMON/phase.txt"     INPUT/phase.txt
ln -sf "../$COMMON/thermo.dat"    INPUT/thermo.dat
ln -sf "../$COMMON/transport.dat" INPUT/transport.dat

cat > input.ini <<'EOI'
[MOSE-Parameters]
iter-threshold = 5
res-threshold  = 1e-300
newrun         = true

[MOSE-Physics]
equations = navier-stokes
schmidt   = 1.0

[MOSE-Numerics]
cfl                   = 0.5
time-accurate         = false
time-scheme           = RK3
integration-variables = cons
space-reconstruction  = MUSCL
flux-limiter          = vanleer
riemann-solver        = HLLC

[MOSE-IO]
sol-format  = vtk raw
shell-diter = 1000000000
EOI

python3 -B ../../../mpi/make_case.py --layout 2x2 --cells 8 8 --bc box --zfaces 300 > /dev/null \
  || { echo "VtkNames: FAIL — case generation"; exit 1; }
rm -rf OUTPUT; mkdir -p OUTPUT
"$LOCAL" > solve.log 2>&1 || { tail -20 solve.log; echo "VtkNames: FAIL — solver exited non-zero"; exit 1; }

python3 -B check_vtk_names.py OUTPUT
