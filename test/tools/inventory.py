#!/usr/bin/env python3
"""Render the list of tests in test/TESTING-PLAN.md from the registrations.

CMake writes <build>/test/inventory.tsv at configure (test/CMakeLists.txt: name, tier, seconds, kind, labels, built,
description). This script puts three tables, one per tier, between the markers

    <!-- tests:begin -->  ...  <!-- tests:end -->

of the plan, so that the list cannot drift from the tests.

    inventory.py <build-dir>             rewrite the tables
    inventory.py <build-dir> --check     exit 1 if the plan is not up to date (CI)

Standard library only.
"""
import argparse
import os
import sys

BEGIN = "<!-- tests:begin (generated by test/tools/inventory.py from test/CMakeLists.txt and test/tiers.txt: do not edit) -->"
END = "<!-- tests:end -->"
TIERS = (("light", "Light", "under 5 s"), ("medium", "Medium", "5 s to 100 s"), ("heavy", "Heavy", "100 s and more, local"))
HERE = os.path.dirname(os.path.abspath(__file__))
PLAN = os.path.join(HERE, "..", "TESTING-PLAN.md")


def seconds(s):
    if s == "-":
        return "-"
    v = float(s)
    return "<0.1" if v < 0.05 else ("%.1f" % v if v < 10 else "%.0f" % v)


def read_inventory(build):
    rows = []
    with open(os.path.join(build, "test", "inventory.tsv")) as fh:
        for line in fh:
            name, tier, sec, kind, labels, built, desc = line.rstrip("\n").split("\t", 6)
            rows.append(dict(name=name, tier=tier, sec=sec, kind=kind, labels=labels.split(","), desc=desc))
    return rows


def render(rows):
    out = [BEGIN, ""]
    for tier, title, bound in TIERS:
        rs = [r for r in rows if r["tier"] == tier]
        measured = [float(r["sec"]) for r in rs if r["sec"] != "-"]
        total = sum(measured)
        if total >= 3600:
            span = "%.1f h" % (total / 3600)
        elif total >= 90:
            span = "%.0f min" % (total / 60)
        else:
            span = "%.0f s" % total
        out.append("#### %s: %s (%d tests, %s)" % (title, bound, len(rs), span))
        out.append("")
        out.append("| Test | Kind | Checks | s |")
        out.append("|---|---|---|--:|")
        for r in rs:
            kind = r["kind"] + (", MPI" if "needs-mpi" in r["labels"] else "")
            out.append("| `%s` | %s | %s | %s |" % (r["name"], kind, r["desc"], seconds(r["sec"])))
        out.append("")
    out.append(END)
    return "\n".join(out)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("build")
    p.add_argument("--plan", default=PLAN)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    text = open(a.plan).read()
    i, j = text.find("<!-- tests:begin"), text.find(END)
    if i < 0 or j < 0:
        sys.exit("%s: the markers '<!-- tests:begin -->' and '%s' are missing" % (a.plan, END))
    new = text[:i] + render(read_inventory(a.build)) + text[j + len(END):]
    if a.check:
        if new != text:
            sys.exit("%s is not up to date: run  python3 test/tools/inventory.py <build-dir>" % a.plan)
        print("the list of tests in %s is up to date" % os.path.basename(a.plan))
        return
    open(a.plan, "w").write(new)
    print("wrote the tables of %s" % a.plan)


if __name__ == "__main__":
    main()
